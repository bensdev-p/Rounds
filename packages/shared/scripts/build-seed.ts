/**
 * Writes supabase/seed.sql from validated content. Run with `pnpm content:seed`.
 *
 * Seeds the fictional test fixtures (tests rely on them) plus the approved and
 * in-review scripts in content/scripts, and turns on the local preview so
 * in-review scripts show (labelled "Not yet reviewed"). Drafts are never seeded.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { checkContent, seedable } from '../src/content/contentFile.ts';
import { buildSeedSql, SeedError } from '../src/db/seed.ts';
import {
  TEST_QUESTION_VARIANTS,
  TEST_QUESTIONS,
  TEST_SCRIPTS,
} from '../src/fixtures/index.ts';
import { fail, loadContent, sha256 } from './content.ts';

const target = fileURLToPath(new URL('../../../supabase/seed.sql', import.meta.url));

const { files, approvals, problems } = loadContent();
const all = [...problems, ...checkContent(files, approvals, sha256)];
if (all.length > 0) fail(all);

const real = seedable(files);
const scripts = [...TEST_SCRIPTS, ...real.scripts];
const questions = [...TEST_QUESTIONS, ...TEST_QUESTION_VARIANTS, ...real.questions];
const linkTargets = new Set([...TEST_SCRIPTS.map((s) => s.id), ...real.linkTargets]);

const describe = (s: (typeof real.scripts)[number]) =>
  s.status === 'approved'
    ? `  ${s.id} v${s.version}, reviewed by ${s.reviewed_by}`
    : `  ${s.id} v${s.version}, IN REVIEW (shown as "Not yet reviewed")`;

const header = [
  'GENERATED by `pnpm content:seed` (packages/shared/scripts/build-seed.ts). Do not edit.',
  '',
  'Local development seed. Runs after migrations on `supabase db reset`.',
  `Fictional test fixtures (${TEST_SCRIPTS.map((s) => s.id).join(', ')}) plus real scripts:`,
  real.scripts.length > 0 ? real.scripts.map(describe).join('\n') : '  (none yet)',
].join('\n');

/** Local development only: students also see in-review scripts, labelled. Never set on a hosted database. */
const PREVIEW_ON = [
  '-- Local preview: show in-review scripts (labelled "Not yet reviewed" in the app).',
  "insert into public.app_settings (key, value) values ('show_in_review', true)",
  '  on conflict (key) do update set value = excluded.value;',
  '',
].join('\n');

try {
  writeFileSync(target, `${buildSeedSql(scripts, questions, header, linkTargets)}\n${PREVIEW_ON}`);
  const inReview = real.scripts.filter((s) => s.status === 'in_review').length;
  console.log(
    `Wrote ${scripts.length} scripts (${real.scripts.length - inReview} approved, ${inReview} in review, plus fixtures) and ${questions.length} questions to ${target}`,
  );
} catch (error) {
  if (error instanceof SeedError) fail([error.message]);
  throw error;
}
