/**
 * Writes supabase/seed.sql from validated content. Run with `pnpm content:seed`.
 *
 * Seeds the fictional test fixtures (tests rely on them) plus every APPROVED
 * script in content/scripts. Drafts and scripts in review are never seeded.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { checkContent, seedable } from '../src/content/contentFile.ts';
import { buildSeedSql, SeedError } from '../src/db/seed.ts';
import { TEST_QUESTIONS, TEST_SCRIPTS } from '../src/fixtures/index.ts';
import { fail, loadContent, sha256 } from './content.ts';

const target = fileURLToPath(new URL('../../../supabase/seed.sql', import.meta.url));

const { files, approvals, problems } = loadContent();
const all = [...problems, ...checkContent(files, approvals, sha256)];
if (all.length > 0) fail(all);

const real = seedable(files);
const scripts = [...TEST_SCRIPTS, ...real.scripts];
const questions = [...TEST_QUESTIONS, ...real.questions];
const linkTargets = new Set([...TEST_SCRIPTS.map((s) => s.id), ...real.linkTargets]);

const header = [
  'GENERATED by `pnpm content:seed` (packages/shared/scripts/build-seed.ts). Do not edit.',
  '',
  'Local development seed. Runs after migrations on `supabase db reset`.',
  `Fictional test fixtures (${TEST_SCRIPTS.map((s) => s.id).join(', ')}) plus approved scripts:`,
  real.scripts.length > 0
    ? real.scripts.map((s) => `  ${s.id} v${s.version}, reviewed by ${s.reviewed_by}`).join('\n')
    : '  (none yet)',
].join('\n');

try {
  writeFileSync(target, buildSeedSql(scripts, questions, header, linkTargets));
  console.log(
    `Wrote ${scripts.length} scripts (${real.scripts.length} approved real) and ${questions.length} questions to ${target}`,
  );
} catch (error) {
  if (error instanceof SeedError) fail([error.message]);
  throw error;
}
