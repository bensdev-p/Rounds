/**
 * `pnpm content:push`: brings the linked hosted project's scripts and questions
 * in line with content/scripts (approved and in-review only, never the test
 * fixtures). See docs/HOSTING.md.
 *
 *   --preview   also show in-review scripts, labelled "Not yet reviewed". Only
 *               for a project listed in supabase/hosting.json → previewProjects
 *               (the private dev project; domain rule 2). Without it the
 *               preview is turned off.
 *   --dry-run   validate and write the SQL, but don't run it.
 *   --yes       don't ask before changing the hosted database.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkContent, seedable } from '../src/content/contentFile.ts';
import { buildContentSql, SeedError } from '../src/db/seed.ts';
import { fail, loadContent, sha256 } from './content.ts';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const args = new Set(process.argv.slice(2));
const preview = args.has('--preview');
const dryRun = args.has('--dry-run');

const refFile = join(root, 'supabase/.temp/project-ref');
const ref = existsSync(refFile) ? readFileSync(refFile, 'utf8').trim() : '';
if (!ref && !dryRun) {
  fail(['No linked hosted project. Run `pnpm supabase link` first (docs/HOSTING.md).']);
}

const hosting = JSON.parse(readFileSync(join(root, 'supabase/hosting.json'), 'utf8')) as {
  previewProjects?: string[];
};
if (preview && ref && !(hosting.previewProjects ?? []).includes(ref)) {
  fail([
    `Project ${ref} isn't in supabase/hosting.json → previewProjects, so it may show approved scripts only (domain rule 2). Drop --preview.`,
  ]);
}

const { files, approvals, problems } = loadContent();
const all = [...problems, ...checkContent(files, approvals, sha256)];
if (all.length > 0) fail(all);

const real = seedable(files);
const approved = real.scripts.filter((s) => s.status === 'approved').length;
const shown = preview ? real.scripts.length : approved;
const header = [
  'GENERATED by `pnpm content:push` (packages/shared/scripts/push-content.ts).',
  `Target: ${ref || '(none linked)'}. Preview ${preview ? 'on' : 'off'}.`,
].join('\n');

let sql: string;
try {
  sql = buildContentSql(real.scripts, real.questions, header, { preview }, real.linkTargets);
} catch (error) {
  if (error instanceof SeedError) fail([error.message]);
  throw error;
}

const file = join(tmpdir(), 'rounds-content-push.sql');
writeFileSync(file, sql);
console.log(
  `${real.scripts.length} scripts (${approved} approved, ${real.scripts.length - approved} in review) and ${real.questions.length} questions. Students will see ${shown} scripts.`,
);

if (dryRun) {
  console.log(`Dry run: SQL written to ${file}, nothing sent.`);
  process.exit(0);
}

console.log(`Pushing to ${ref}…`);
const command = ['supabase', 'db', 'query', '--remote', '--file', file];
if (args.has('--yes')) command.push('--yes');
const result = spawnSync('pnpm', ['exec', ...command], {
  cwd: root,
  stdio: 'inherit',
  shell: process.platform === 'win32',
});
process.exit(result.status ?? 1);
